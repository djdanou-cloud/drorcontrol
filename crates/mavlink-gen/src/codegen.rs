//! Rust source generation for a resolved [`Dialect`].
//!
//! The generated code targets the runtime API of the `mavlink-codec` crate
//! (`crate::MessageData`, `crate::wire`, `crate::FieldValue`, `crate::MessageInfo`,
//! `crate::UnknownMessage`) and is meant to be `include!`d inside it.

use std::collections::HashSet;
use std::fmt::Write as _;

use crate::model::{Dialect, Enum, Field, Message, Prim};

/// Generate the dialect module source. `root` is recorded in the output for traceability.
pub fn generate(dialect: &Dialect, root: &str) -> String {
    let mut o = String::with_capacity(1 << 20);
    let _ = writeln!(
        o,
        "// @generated by mavlink-gen from {root}. Do not edit.\n"
    );
    let _ = writeln!(o, "/// Root XML file this dialect was generated from.");
    let _ = writeln!(o, "pub const DIALECT_ROOT: &str = {root:?};\n");

    o.push_str(
        "/// Enum definitions. Values are newtypes so unknown values survive a round trip.\n",
    );
    o.push_str("pub mod enums {\n");
    for e in &dialect.enums {
        gen_enum(&mut o, e);
    }
    o.push_str("}\n\n");

    o.push_str("/// Message definitions (fields in XML declaration order; wire order is handled internally).\n");
    o.push_str("pub mod messages {\n    use crate::wire::{Reader, Writer};\n    use crate::{FieldValue, MessageData};\n\n");
    for m in &dialect.messages {
        gen_message(&mut o, m);
    }
    o.push_str("}\n\n");

    gen_message_enum(&mut o, &dialect.messages);
    gen_info_table(&mut o, &dialect.messages);
    o
}

/// `GPS_RAW_INT` -> `GpsRawInt`.
pub fn camel(name: &str) -> String {
    name.split('_')
        .filter(|p| !p.is_empty())
        .map(|p| {
            let lower = p.to_ascii_lowercase();
            let mut c = lower.chars();
            match c.next() {
                Some(f) => f.to_ascii_uppercase().to_string() + c.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

const KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "dyn", "else", "enum", "extern", "false",
    "fn", "for", "gen", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub",
    "ref", "return", "static", "struct", "trait", "true", "type", "unsafe", "use", "where",
    "while", "abstract", "become", "box", "do", "final", "macro", "override", "priv", "try",
    "typeof", "unsized", "virtual", "yield",
];

/// A field name as a Rust identifier (`type` -> `r#type`).
pub fn ident(name: &str) -> String {
    if matches!(name, "self" | "Self" | "super" | "crate") {
        format!("{name}_")
    } else if KEYWORDS.contains(&name) {
        format!("r#{name}")
    } else {
        name.to_string()
    }
}

fn doc(o: &mut String, indent: &str, text: &str) {
    for line in text.lines() {
        let line = line.trim();
        if !line.is_empty() {
            let _ = writeln!(o, "{indent}/// {line}");
        }
    }
}

fn enum_repr(e: &Enum) -> &'static str {
    let max = e.entries.iter().map(|x| x.value).max().unwrap_or(0);
    if max <= u64::from(u8::MAX) {
        "u8"
    } else if max <= u64::from(u16::MAX) {
        "u16"
    } else if max <= u64::from(u32::MAX) {
        "u32"
    } else {
        "u64"
    }
}

/// Const names: entry name minus the enum-name prefix, unless that would be invalid or clash.
fn const_names(e: &Enum) -> Vec<String> {
    let prefix = format!("{}_", e.name);
    let short: Vec<String> = e
        .entries
        .iter()
        .map(|x| match x.name.strip_prefix(&prefix) {
            Some(s) if !s.is_empty() && !s.starts_with(|c: char| c.is_ascii_digit()) => {
                s.to_string()
            }
            _ => x.name.clone(),
        })
        .collect();
    let mut seen = HashSet::new();
    let dup: HashSet<&String> = short.iter().filter(|s| !seen.insert(*s)).collect();
    short
        .iter()
        .zip(&e.entries)
        .map(|(s, x)| {
            if dup.contains(s) {
                x.name.clone()
            } else {
                s.clone()
            }
        })
        .collect()
}

fn gen_enum(o: &mut String, e: &Enum) {
    let ty = camel(&e.name);
    let repr = enum_repr(e);
    doc(o, "    ", &e.description);
    let _ = writeln!(
        o,
        "    ///\n    /// MAVLink enum `{}`{}.",
        e.name,
        if e.bitmask { " (bitmask)" } else { "" }
    );
    let _ = writeln!(
        o,
        "    #[derive(Copy, Clone, Debug, Default, PartialEq, Eq, Hash, PartialOrd, Ord)]"
    );
    let _ = writeln!(
        o,
        "    #[repr(transparent)]\n    pub struct {ty}(pub {repr});\n"
    );
    let _ = writeln!(o, "    impl {ty} {{");
    let names = const_names(e);
    for (x, c) in e.entries.iter().zip(&names) {
        doc(o, "        ", &x.description);
        if x.deprecated {
            let _ = writeln!(o, "        ///\n        /// Deprecated upstream.");
        }
        let _ = writeln!(o, "        pub const {c}: Self = Self({});", x.value);
    }
    let _ = writeln!(
        o,
        "\n        /// Upstream entry name for this value, if it is a defined entry."
    );
    let _ = writeln!(
        o,
        "        pub fn name(self) -> Option<&'static str> {{\n            match self.0 {{"
    );
    let mut seen = HashSet::new();
    for x in &e.entries {
        if seen.insert(x.value) {
            let _ = writeln!(o, "                {} => Some({:?}),", x.value, x.name);
        }
    }
    let _ = writeln!(o, "                _ => None,\n            }}\n        }}");
    if e.bitmask {
        let _ = writeln!(
            o,
            "\n        /// True if every bit of `flag` is set in `self`."
        );
        let _ = writeln!(
            o,
            "        pub fn contains(self, flag: Self) -> bool {{\n            self.0 & flag.0 == flag.0\n        }}"
        );
    }
    let _ = writeln!(o, "    }}\n");
    if e.bitmask {
        let _ = writeln!(
            o,
            "    impl core::ops::BitOr for {ty} {{\n        type Output = Self;\n        fn bitor(self, rhs: Self) -> Self {{\n            Self(self.0 | rhs.0)\n        }}\n    }}\n"
        );
    }
}

fn rust_type(f: &Field) -> String {
    match f.ty.array_len {
        Some(n) => format!("[{}; {n}]", f.ty.prim.rust()),
        None => f.ty.prim.rust().to_string(),
    }
}

fn zero(f: &Field) -> String {
    let z = match f.ty.prim {
        Prim::F32 | Prim::F64 => "0.0",
        _ => "0",
    };
    match f.ty.array_len {
        Some(n) => format!("[{z}; {n}]"),
        None => z.to_string(),
    }
}

fn field_value(f: &Field) -> String {
    let id = ident(&f.name);
    let (kind, conv) = match f.ty.prim {
        Prim::Char if f.ty.array_len.is_some() => {
            return format!("FieldValue::Chars(self.{id}.to_vec())");
        }
        Prim::Char => return format!("FieldValue::Chars(vec![self.{id}])"),
        Prim::F32 | Prim::F64 => ("Float", "f64::from"),
        Prim::I8 | Prim::I16 | Prim::I32 | Prim::I64 => ("Int", "i64::from"),
        _ => ("UInt", "u64::from"),
    };
    match f.ty.array_len {
        Some(_) => {
            format!("FieldValue::{kind}Array(self.{id}.iter().map(|v| {conv}(*v)).collect())")
        }
        None => format!("FieldValue::{kind}({conv}(self.{id}))"),
    }
}

fn gen_message(o: &mut String, m: &Message) {
    let ty = camel(&m.name);
    doc(o, "    ", &m.description);
    let _ = writeln!(
        o,
        "    ///\n    /// MAVLink message `{}` (id {}, CRC_EXTRA {}, payload {}..={} bytes, from `{}`).",
        m.name,
        m.id,
        m.crc_extra(),
        m.base_len(),
        m.max_len(),
        m.source
    );
    if m.deprecated {
        let _ = writeln!(o, "    /// Deprecated upstream.");
    }
    if m.wip {
        let _ = writeln!(o, "    /// Work in progress upstream: layout may change.");
    }
    let _ = writeln!(
        o,
        "    #[derive(Clone, Debug, PartialEq)]\n    pub struct {ty} {{"
    );
    for f in &m.fields {
        doc(o, "        ", &f.description);
        let mut notes = Vec::new();
        if let Some(u) = &f.units {
            notes.push(format!("Units: `{u}`."));
        }
        if let Some(e) = &f.enum_name {
            notes.push(format!("Values: [`super::enums::{}`].", camel(e)));
        }
        if f.extension {
            notes.push("MAVLink 2 extension field.".into());
        }
        if !notes.is_empty() {
            let _ = writeln!(o, "        ///\n        /// {}", notes.join(" "));
        }
        let _ = writeln!(o, "        pub {}: {},", ident(&f.name), rust_type(f));
    }
    let _ = writeln!(o, "    }}\n");

    let _ = writeln!(
        o,
        "    impl Default for {ty} {{\n        fn default() -> Self {{\n            Self {{"
    );
    for f in &m.fields {
        let _ = writeln!(o, "                {}: {},", ident(&f.name), zero(f));
    }
    let _ = writeln!(o, "            }}\n        }}\n    }}\n");

    let _ = writeln!(o, "    impl MessageData for {ty} {{");
    let _ = writeln!(o, "        const ID: u32 = {};", m.id);
    let _ = writeln!(o, "        const NAME: &'static str = {:?};", m.name);
    let _ = writeln!(o, "        const CRC_EXTRA: u8 = {};", m.crc_extra());
    let _ = writeln!(o, "        const BASE_LEN: usize = {};", m.base_len());
    let _ = writeln!(o, "        const MAX_LEN: usize = {};\n", m.max_len());

    let wire = m.wire_fields();
    let _ = writeln!(
        o,
        "        fn serialize(&self, out: &mut [u8; 255]) -> usize {{\n            let mut w = Writer::new(out);"
    );
    for f in &wire {
        let id = ident(&f.name);
        let p = f.ty.prim.rust();
        match (f.ty.prim, f.ty.array_len) {
            (Prim::Char | Prim::U8 | Prim::U8MavlinkVersion, Some(_)) => {
                let _ = writeln!(o, "            w.put_bytes(&self.{id});");
            }
            (_, Some(_)) => {
                let _ = writeln!(
                    o,
                    "            for v in &self.{id} {{\n                w.put_{p}(*v);\n            }}"
                );
            }
            (_, None) => {
                let _ = writeln!(o, "            w.put_{p}(self.{id});");
            }
        }
    }
    let _ = writeln!(o, "            w.len()\n        }}\n");

    let _ = writeln!(
        o,
        "        fn deserialize(payload: &[u8]) -> Self {{\n            let mut r = Reader::new(payload);\n            let mut m = Self::default();"
    );
    for f in &wire {
        let id = ident(&f.name);
        let p = f.ty.prim.rust();
        match (f.ty.prim, f.ty.array_len) {
            (Prim::Char | Prim::U8 | Prim::U8MavlinkVersion, Some(_)) => {
                let _ = writeln!(o, "            r.get_bytes(&mut m.{id});");
            }
            (_, Some(_)) => {
                let _ = writeln!(
                    o,
                    "            for v in m.{id}.iter_mut() {{\n                *v = r.get_{p}();\n            }}"
                );
            }
            (_, None) => {
                let _ = writeln!(o, "            m.{id} = r.get_{p}();");
            }
        }
    }
    let _ = writeln!(o, "            m\n        }}\n");

    let _ = writeln!(
        o,
        "        fn fields(&self) -> Vec<(&'static str, FieldValue)> {{\n            vec!["
    );
    for f in &m.fields {
        let _ = writeln!(o, "                ({:?}, {}),", f.name, field_value(f));
    }
    let _ = writeln!(o, "            ]\n        }}\n    }}\n");
}

fn gen_message_enum(o: &mut String, msgs: &[Message]) {
    o.push_str("/// Any message of this dialect.\n#[derive(Clone, Debug, PartialEq)]\n#[allow(clippy::large_enum_variant)]\npub enum Message {\n");
    for m in msgs {
        let _ = writeln!(
            o,
            "    /// `{}` (id {}).\n    {}(messages::{}),",
            m.name,
            m.id,
            camel(&m.name),
            camel(&m.name)
        );
    }
    o.push_str("}\n\n");

    o.push_str("impl Message {\n");
    o.push_str("    /// Decode a payload for message `id` (zero-extending truncated MAVLink 2 payloads).\n");
    o.push_str("    pub fn parse(id: u32, payload: &[u8]) -> Result<Self, crate::UnknownMessage> {\n        use crate::MessageData;\n        Ok(match id {\n");
    for m in msgs {
        let c = camel(&m.name);
        let _ = writeln!(
            o,
            "            {} => Message::{c}(messages::{c}::deserialize(payload)),",
            m.id
        );
    }
    o.push_str("            _ => return Err(crate::UnknownMessage(id)),\n        })\n    }\n\n");

    for (fname, ret, doc_s, body) in [
        (
            "id",
            "u32",
            "Message ID.",
            "<messages::{} as crate::MessageData>::ID",
        ),
        (
            "name",
            "&'static str",
            "Upstream message name.",
            "<messages::{} as crate::MessageData>::NAME",
        ),
        (
            "crc_extra",
            "u8",
            "CRC_EXTRA seed for this message.",
            "<messages::{} as crate::MessageData>::CRC_EXTRA",
        ),
    ] {
        let _ = writeln!(
            o,
            "    /// {doc_s}\n    pub fn {fname}(&self) -> {ret} {{\n        match self {{"
        );
        for m in msgs {
            let c = camel(&m.name);
            let _ = writeln!(
                o,
                "            Message::{c}(_) => {},",
                body.replace("{}", &c)
            );
        }
        o.push_str("        }\n    }\n\n");
    }

    o.push_str(
        "    /// Serialize the full (untruncated) payload into `out`; returns its length.\n",
    );
    o.push_str("    pub fn serialize(&self, out: &mut [u8; 255]) -> usize {\n        use crate::MessageData;\n        match self {\n");
    for m in msgs {
        let _ = writeln!(
            o,
            "            Message::{}(m) => m.serialize(out),",
            camel(&m.name)
        );
    }
    o.push_str("        }\n    }\n\n");

    o.push_str(
        "    /// Field names and values in declaration order (for inspectors, logs and tests).\n",
    );
    o.push_str("    pub fn fields(&self) -> Vec<(&'static str, crate::FieldValue)> {\n        use crate::MessageData;\n        match self {\n");
    for m in msgs {
        let _ = writeln!(
            o,
            "            Message::{}(m) => m.fields(),",
            camel(&m.name)
        );
    }
    o.push_str("        }\n    }\n}\n\n");
}

/// Routing target field. MANUAL_CONTROL names it `target` (same special case as pymavlink).
fn target_system_offset(m: &Message) -> Option<usize> {
    m.u8_field_offset("target_system").or_else(|| {
        if m.name == "MANUAL_CONTROL" {
            m.u8_field_offset("target")
        } else {
            None
        }
    })
}

fn gen_info_table(o: &mut String, msgs: &[Message]) {
    let _ = writeln!(
        o,
        "static MESSAGE_INFO: [crate::MessageInfo; {}] = [",
        msgs.len()
    );
    for m in msgs {
        let _ = writeln!(
            o,
            "    crate::MessageInfo {{ id: {}, name: {:?}, crc_extra: {}, base_len: {}, max_len: {}, target_system_ofs: {:?}, target_component_ofs: {:?} }},",
            m.id,
            m.name,
            m.crc_extra(),
            m.base_len(),
            m.max_len(),
            target_system_offset(m),
            m.u8_field_offset("target_component"),
        );
    }
    o.push_str("];\n\n");
    o.push_str("/// Wire metadata for message `id`, without decoding anything (used by the framer and router).\n");
    o.push_str("pub fn message_info(id: u32) -> Option<&'static crate::MessageInfo> {\n    MESSAGE_INFO.binary_search_by_key(&id, |m| m.id).ok().map(|i| &MESSAGE_INFO[i])\n}\n\n");
    o.push_str("/// Wire metadata for every message, sorted by ID.\npub fn message_infos() -> &'static [crate::MessageInfo] {\n    &MESSAGE_INFO\n}\n");
    gen_layout_table(o, msgs);
}

/// Every field's wire position, so tools can find fields by name or units without decoding
/// (e.g. every `degE7` position for log sanitising).
fn gen_layout_table(o: &mut String, msgs: &[Message]) {
    let n: usize = msgs.iter().map(|m| m.fields.len()).sum();
    let _ = writeln!(o, "\nstatic FIELD_LAYOUT: [crate::FieldLayout; {n}] = [");
    for m in msgs {
        let mut ofs = 0;
        for f in m.wire_fields() {
            let _ = writeln!(
                o,
                "    crate::FieldLayout {{ msg_id: {}, name: {:?}, offset: {ofs}, ty: {:?}, array_len: {}, units: {:?}, extension: {} }},",
                m.id,
                f.name,
                f.ty.prim.crc_name(),
                f.ty.array_len.unwrap_or(0),
                f.units,
                f.extension,
            );
            ofs += f.ty.wire_size();
        }
    }
    o.push_str("];\n\n");
    o.push_str("/// Fields of message `id` in wire order (empty for an unknown ID).\npub fn message_fields(id: u32) -> &'static [crate::FieldLayout] {\n    let a = FIELD_LAYOUT.partition_point(|f| f.msg_id < id);\n    let b = FIELD_LAYOUT.partition_point(|f| f.msg_id <= id);\n    &FIELD_LAYOUT[a..b]\n}\n");
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names() {
        assert_eq!(camel("GPS_RAW_INT"), "GpsRawInt");
        assert_eq!(camel("SCALED_IMU2"), "ScaledImu2");
        assert_eq!(camel("MAV_CMD"), "MavCmd");
        assert_eq!(ident("type"), "r#type");
        assert_eq!(ident("self"), "self_");
        assert_eq!(ident("roll"), "roll");
    }

    #[test]
    fn const_names_strip_prefix_but_stay_valid() {
        use crate::model::Entry;
        let entry = |n: &str, v| Entry {
            name: n.into(),
            value: v,
            description: String::new(),
            deprecated: false,
        };
        let e = Enum {
            name: "GPS_FIX_TYPE".into(),
            bitmask: false,
            description: String::new(),
            entries: vec![
                entry("GPS_FIX_TYPE_NO_GPS", 0),
                entry("GPS_FIX_TYPE_3D_FIX", 3),
            ],
        };
        assert_eq!(const_names(&e), ["NO_GPS", "GPS_FIX_TYPE_3D_FIX"]);
        assert_eq!(enum_repr(&e), "u8");
    }
}
