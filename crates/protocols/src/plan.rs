//! QGroundControl plan files (`.plan`, JSON): mission, geofence and rally points in one file.
//!
//! Format (QGroundControl developer guide, "Plan File Format", `file_formats/plan.md`):
//! top level `fileType` "Plan", `version` 1, `groundStation`, `mission`, optional `geoFence`
//! and `rallyPoints`. `mission.items` holds `SimpleItem`s: `command` (MAV_CMD), `frame`
//! (MAV_FRAME), `params` (seven numbers: param1–4, then x, y, z, i.e. latitude, longitude
//! and altitude in a global frame; `null` for an unset value), `autoContinue`, `doJumpId`.
//! `mission.plannedHomePosition` is `[lat, lon, AMSL alt]`. `geoFence.polygons[]` =
//! `{inclusion, polygon: [[lat, lon]…], version}`, `geoFence.circles[]` =
//! `{circle: {center: [lat, lon], radius}, inclusion, version}`; `rallyPoints.points[]` =
//! `[lat, lon, alt above home]`.
//!
//! Here the items become the same [`MissionItem`]s a `.waypoints` file gives, with home as
//! item 0; the fence becomes the ArduPilot fence items (`NAV_FENCE_POLYGON_VERTEX_*` 5001/5002
//! with param1 = vertex count, `NAV_FENCE_CIRCLE_*` 5003/5004 with param1 = radius) and the
//! rally points `NAV_RALLY_POINT` 5100 in the relative-altitude frame. QGroundControl
//! "ComplexItem"s (surveys, corridor scans drawn in QGC) are refused by name: their flight
//! path is generated by QGC and not stored as items.

use serde_json::{Value, json};

use crate::mission::MissionItem;

/// A plan: mission (item 0 = home), fence items and rally items.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct Plan {
    /// Mission items; item 0 is home (from `plannedHomePosition`).
    pub mission: Vec<MissionItem>,
    /// Geofence items (5001–5004).
    pub fence: Vec<MissionItem>,
    /// Rally points (5100).
    pub rally: Vec<MissionItem>,
}

/// Why a plan file could not be read.
#[derive(Debug, Clone, PartialEq)]
pub enum PlanError {
    /// Not JSON.
    Json(String),
    /// JSON, but not a plan this reader understands.
    Format(String),
}

impl std::fmt::Display for PlanError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            PlanError::Json(e) => write!(f, "not JSON: {e}"),
            PlanError::Format(e) => write!(f, "not a usable .plan file: {e}"),
        }
    }
}

impl std::error::Error for PlanError {}

const GLOBAL_FRAMES: [u8; 6] = [0, 3, 5, 6, 10, 11];

fn bad(what: impl Into<String>) -> PlanError {
    PlanError::Format(what.into())
}

fn num(v: &Value) -> f64 {
    v.as_f64().unwrap_or(f64::NAN)
}

fn deg_e7(d: f64) -> i32 {
    (d * 1e7).round() as i32
}

fn item(frame: u8, command: u16, p: [f64; 7], autocontinue: bool) -> MissionItem {
    let global = GLOBAL_FRAMES.contains(&frame);
    let xy = |v: f64| {
        if !v.is_finite() {
            0
        } else if global {
            deg_e7(v)
        } else {
            v.round() as i32
        }
    };
    MissionItem {
        frame,
        command,
        params: [p[0] as f32, p[1] as f32, p[2] as f32, p[3] as f32],
        x: xy(p[4]),
        y: xy(p[5]),
        z: if p[6].is_finite() { p[6] as f32 } else { 0.0 },
        autocontinue,
    }
}

/// Read a `.plan` file.
pub fn parse(text: &str) -> Result<Plan, PlanError> {
    let v: Value = serde_json::from_str(text).map_err(|e| PlanError::Json(e.to_string()))?;
    if v["fileType"] != "Plan" {
        return Err(bad("fileType is not \"Plan\""));
    }
    let m = &v["mission"];
    let home = m["plannedHomePosition"]
        .as_array()
        .filter(|a| a.len() >= 3)
        .ok_or_else(|| bad("mission.plannedHomePosition missing"))?;
    let mut plan = Plan::default();
    plan.mission.push(item(
        0,
        16,
        [
            0.0,
            0.0,
            0.0,
            0.0,
            num(&home[0]),
            num(&home[1]),
            num(&home[2]),
        ],
        true,
    ));
    for (i, it) in m["items"]
        .as_array()
        .ok_or_else(|| bad("mission.items missing"))?
        .iter()
        .enumerate()
    {
        match it["type"].as_str() {
            Some("SimpleItem") => {}
            Some(other) => {
                return Err(bad(format!(
                    "item {} is a QGroundControl {other} (e.g. a survey drawn in QGC): its path is not stored in the file; open it in QGC and save the mission as .waypoints, or plan it here",
                    i + 1
                )));
            }
            None => return Err(bad(format!("item {} has no type", i + 1))),
        }
        let p = it["params"]
            .as_array()
            .filter(|p| p.len() == 7)
            .ok_or_else(|| bad(format!("item {}: params must have 7 values", i + 1)))?;
        let mut vals = [0.0; 7];
        for (d, s) in vals.iter_mut().zip(p) {
            *d = num(s);
        }
        let command = it["command"]
            .as_u64()
            .and_then(|c| u16::try_from(c).ok())
            .ok_or_else(|| bad(format!("item {}: command", i + 1)))?;
        let frame = it["frame"]
            .as_u64()
            .and_then(|f| u8::try_from(f).ok())
            .ok_or_else(|| bad(format!("item {}: frame", i + 1)))?;
        plan.mission.push(item(
            frame,
            command,
            vals,
            it["autoContinue"].as_bool().unwrap_or(true),
        ));
    }
    let f = &v["geoFence"];
    for poly in f["polygons"].as_array().into_iter().flatten() {
        let pts = poly["polygon"]
            .as_array()
            .ok_or_else(|| bad("geoFence polygon without points"))?;
        let cmd = if poly["inclusion"].as_bool().unwrap_or(true) {
            5001
        } else {
            5002
        };
        for pt in pts {
            let ll = pt
                .as_array()
                .filter(|a| a.len() >= 2)
                .ok_or_else(|| bad("fence point"))?;
            plan.fence.push(item(
                0,
                cmd,
                [
                    pts.len() as f64,
                    0.0,
                    0.0,
                    0.0,
                    num(&ll[0]),
                    num(&ll[1]),
                    0.0,
                ],
                true,
            ));
        }
    }
    for c in f["circles"].as_array().into_iter().flatten() {
        let centre = c["circle"]["center"]
            .as_array()
            .filter(|a| a.len() >= 2)
            .ok_or_else(|| bad("fence circle without a centre"))?;
        let cmd = if c["inclusion"].as_bool().unwrap_or(true) {
            5003
        } else {
            5004
        };
        plan.fence.push(item(
            0,
            cmd,
            [
                num(&c["circle"]["radius"]),
                0.0,
                0.0,
                0.0,
                num(&centre[0]),
                num(&centre[1]),
                0.0,
            ],
            true,
        ));
    }
    for pt in v["rallyPoints"]["points"].as_array().into_iter().flatten() {
        let a = pt
            .as_array()
            .filter(|a| a.len() >= 3)
            .ok_or_else(|| bad("rally point"))?;
        plan.rally.push(item(
            3,
            5100,
            [0.0, 0.0, 0.0, 0.0, num(&a[0]), num(&a[1]), num(&a[2])],
            true,
        ));
    }
    Ok(plan)
}

fn xy_out(frame: u8, v: i32) -> Value {
    if GLOBAL_FRAMES.contains(&frame) {
        json!(f64::from(v) / 1e7)
    } else {
        json!(v)
    }
}

fn param(v: f32) -> Value {
    if v.is_finite() {
        json!(f64::from(v))
    } else {
        Value::Null
    }
}

/// Write a `.plan` file (`groundStation` "DrorControl").
pub fn to_string(plan: &Plan) -> String {
    let home = plan.mission.first();
    let items: Vec<Value> = plan
        .mission
        .iter()
        .skip(1)
        .enumerate()
        .map(|(i, m)| {
            json!({
                "type": "SimpleItem",
                "command": m.command,
                "frame": m.frame,
                "params": [param(m.params[0]), param(m.params[1]), param(m.params[2]), param(m.params[3]),
                           xy_out(m.frame, m.x), xy_out(m.frame, m.y), param(m.z)],
                "autoContinue": m.autocontinue,
                "doJumpId": i + 1,
            })
        })
        .collect();
    // Fence vertices come in runs whose param1 is the vertex count.
    let mut polygons = Vec::new();
    let mut circles = Vec::new();
    let mut k = 0;
    while k < plan.fence.len() {
        let f = &plan.fence[k];
        match f.command {
            5001 | 5002 => {
                let n = (f.params[0].max(1.0) as usize).min(plan.fence.len() - k);
                let pts: Vec<Value> = plan.fence[k..k + n]
                    .iter()
                    .map(|p| json!([f64::from(p.x) / 1e7, f64::from(p.y) / 1e7]))
                    .collect();
                polygons
                    .push(json!({"inclusion": f.command == 5001, "polygon": pts, "version": 1}));
                k += n;
            }
            5003 | 5004 => {
                circles.push(json!({
                    "circle": {"center": [f64::from(f.x) / 1e7, f64::from(f.y) / 1e7], "radius": f.params[0]},
                    "inclusion": f.command == 5003,
                    "version": 1,
                }));
                k += 1;
            }
            _ => k += 1,
        }
    }
    let rally: Vec<Value> = plan
        .rally
        .iter()
        .map(|r| json!([f64::from(r.x) / 1e7, f64::from(r.y) / 1e7, r.z]))
        .collect();
    let doc = json!({
        "fileType": "Plan",
        "version": 1,
        "groundStation": "DrorControl",
        "mission": {
            "version": 2,
            "firmwareType": 3,
            "items": items,
            "plannedHomePosition": home.map_or(json!([0.0, 0.0, 0.0]), |h| json!([
                f64::from(h.x) / 1e7, f64::from(h.y) / 1e7, h.z
            ])),
        },
        "geoFence": {"version": 2, "polygons": polygons, "circles": circles},
        "rallyPoints": {"version": 2, "points": rally},
    });
    serde_json::to_string_pretty(&doc).expect("JSON values serialise") + "\n"
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE: &str = r#"{
      "fileType": "Plan", "groundStation": "QGroundControl", "version": 1,
      "mission": {
        "version": 2, "firmwareType": 3, "vehicleType": 2, "cruiseSpeed": 15, "hoverSpeed": 5,
        "plannedHomePosition": [47.3977419, 8.5455938, 487.989],
        "items": [
          {"type": "SimpleItem", "command": 22, "frame": 3, "autoContinue": true, "doJumpId": 1,
           "params": [15, 0, 0, null, 47.3985099, 8.5451002, 50],
           "AMSLAltAboveTerrain": null, "Altitude": 50, "AltitudeMode": 1},
          {"type": "SimpleItem", "command": 178, "frame": 2, "autoContinue": true, "doJumpId": 2,
           "params": [1, 5, -1, 0, 0, 0, 0]}
        ]
      },
      "geoFence": {"version": 2,
        "polygons": [{"inclusion": true, "version": 1,
          "polygon": [[47.39, 8.54], [47.40, 8.54], [47.40, 8.55]]}],
        "circles": [{"inclusion": false, "version": 1,
          "circle": {"center": [47.395, 8.545], "radius": 20}}]},
      "rallyPoints": {"version": 2, "points": [[47.3988, 8.5459, 50]]}
    }"#;

    #[test]
    fn reads_the_documented_layout() {
        let p = parse(SAMPLE).unwrap();
        assert_eq!(p.mission.len(), 3, "home + 2 items");
        let h = p.mission[0];
        assert_eq!((h.command, h.x, h.y), (16, 473_977_419, 85_455_938));
        assert!((h.z - 487.989).abs() < 1e-3);
        let t = p.mission[1];
        assert_eq!(
            (t.command, t.frame, t.x, t.y, t.z),
            (22, 3, 473_985_099, 85_451_002, 50.0)
        );
        assert_eq!(t.params[0], 15.0);
        assert!(t.params[3].is_nan(), "null is an unset value");
        let s = p.mission[2];
        assert_eq!((s.command, s.frame, s.params[1]), (178, 2, 5.0));
        assert_eq!(p.fence.len(), 4);
        assert_eq!(
            p.fence
                .iter()
                .map(|f| (f.command, f.params[0]))
                .collect::<Vec<_>>(),
            [(5001, 3.0), (5001, 3.0), (5001, 3.0), (5004, 20.0)]
        );
        assert_eq!(p.rally.len(), 1);
        assert_eq!(
            (p.rally[0].command, p.rally[0].frame, p.rally[0].z),
            (5100, 3, 50.0)
        );
    }

    #[test]
    fn round_trips() {
        let p = parse(SAMPLE).unwrap();
        let again = parse(&to_string(&p)).unwrap();
        assert_eq!(again.mission.len(), p.mission.len());
        for (a, b) in again.mission.iter().zip(&p.mission) {
            assert_eq!(
                (a.command, a.frame, a.x, a.y, a.z),
                (b.command, b.frame, b.x, b.y, b.z)
            );
            for (x, y) in a.params.iter().zip(&b.params) {
                assert!(x == y || (x.is_nan() && y.is_nan()));
            }
        }
        assert_eq!(again.fence, p.fence);
        assert_eq!(again.rally, p.rally);
    }

    #[test]
    fn refuses_qgc_complex_items_by_name() {
        let t = SAMPLE.replace(
            r#"{"type": "SimpleItem", "command": 178"#,
            r#"{"type": "ComplexItem", "complexItemType": "survey", "command": 178"#,
        );
        let e = parse(&t).unwrap_err().to_string();
        assert!(e.contains("ComplexItem") && e.contains("item 2"), "{e}");
        assert!(parse("{}").is_err());
        assert!(parse("not json").is_err());
    }
}
