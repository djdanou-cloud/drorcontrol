#!/usr/bin/env python3
"""Generate docs/plan/adr/README.md (the ADR index) from the ADR files.

    python3 scripts/gen_adr_index.py           # rewrite the index
    python3 scripts/gen_adr_index.py --check   # exit 1 if it is stale or an ADR is malformed (CI)

Each ADR is `NNNN-slug.md` with a `# ADR-NNNN: Title` heading and `* Status:` / `* Date:` lines
(template: 0000-template.md). Status must start with proposed, accepted, deprecated or
superseded; "superseded by ADR-XXXX" must name an existing ADR.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ADR = ROOT / "docs/plan/adr"
INDEX = ADR / "README.md"
STATUSES = ("proposed", "accepted", "deprecated", "superseded")

HEADER = """# Architecture Decision Records

<!-- GENERATED by scripts/gen_adr_index.py from the ADR files. Do not edit; run the script. -->

Process and template: see [`../06-documentation-system.md`](../06-documentation-system.md) §4.2 and
[`0000-template.md`](0000-template.md). Accepted ADRs are immutable; supersede instead of editing.
"""


def plain(s: str) -> str:
    """Markdown emphasis and code markers removed, for a table cell."""
    return re.sub(r"[*`]", "", s).replace("|", "/").strip()


def read(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    num = path.name[:4]
    m = re.search(r"^# ADR-(\d{4}):\s*(.+)$", text, re.M)
    if not m:
        raise ValueError(f"{path.name}: missing '# ADR-NNNN: Title' heading")
    if m.group(1) != num:
        raise ValueError(f"{path.name}: heading says ADR-{m.group(1)}")
    status = re.search(r"^\*\s*Status:\s*(.+)$", text, re.M)
    if not status:
        raise ValueError(f"{path.name}: missing '* Status:' line")
    word = plain(status.group(1)).split()[0].lower()
    if word not in STATUSES:
        raise ValueError(f"{path.name}: status must start with one of {STATUSES}")
    date = re.search(r"^\*\s*Date:\s*(\d{4}-\d{2}-\d{2})", text, re.M)
    sup = re.search(r"superseded by ADR-(\d{4})", status.group(1), re.I)
    return {"num": num, "file": path.name, "title": plain(m.group(2)), "status": plain(status.group(1)),
            "word": word, "date": date.group(1) if date else "", "superseded_by": sup.group(1) if sup else None}


def build() -> str:
    adrs = [read(p) for p in sorted(ADR.glob("[0-9][0-9][0-9][0-9]-*.md")) if not p.name.startswith("0000-")]
    nums = [a["num"] for a in adrs]
    dup = {n for n in nums if nums.count(n) > 1}
    if dup:
        raise ValueError(f"duplicate ADR numbers: {sorted(dup)}")
    for a in adrs:
        if a["superseded_by"] and a["superseded_by"] not in nums:
            raise ValueError(f"{a['file']}: superseded by unknown ADR-{a['superseded_by']}")
    rows = ["| ADR | Title | Status | Date |", "|-----|-------|--------|------|"]
    for a in adrs:
        rows.append(f"| [{a['num']}]({a['file']}) | {a['title']} | {a['status']} | {a['date']} |")
    counts = {w: sum(a["word"] == w for a in adrs) for w in STATUSES}
    summary = ", ".join(f"{n} {w}" for w, n in counts.items() if n)
    return HEADER + f"\n{len(adrs)} ADRs: {summary}.\n\n" + "\n".join(rows) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    try:
        text = build()
    except ValueError as e:
        sys.exit(f"ADR error: {e}")
    if a.check:
        if INDEX.read_text(encoding="utf-8") != text:
            sys.exit("docs/plan/adr/README.md is stale: run python3 scripts/gen_adr_index.py")
        print("ADR index up to date")
        return
    INDEX.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {INDEX.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
