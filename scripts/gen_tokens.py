#!/usr/bin/env python3
"""Generate the QML singleton and CSS variables from ui/tokens/tokens.json.

    python3 scripts/gen_tokens.py           # write ui/tokens/generated/*
    python3 scripts/gen_tokens.py --check   # exit 1 if the generated files are stale (CI)

QML: add ui/tokens/generated/qml to the import path, `import DrorControl.Tokens`, then `Tokens.canvas`, `Tokens.stateWarning`,
`Tokens.sizeTelemetryL`...; switch themes at runtime with `Tokens.theme = "daylight"`.
CSS: `var(--dc-color-canvas)` etc.; select a theme with `data-theme="daylight"` on any ancestor
(standard is the default). Contrast rules are checked by crates/design-tokens.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "ui/tokens/tokens.json"
OUT = ROOT / "ui/tokens/generated"
HEADER = "GENERATED by scripts/gen_tokens.py from ui/tokens/tokens.json. Do not edit."


def camel(*parts):
    out = parts[0]
    for p in parts[1:]:
        out += p[:1].upper() + p[1:]
    return out


def kebab(s):
    return re.sub(r"([A-Z])", lambda m: "-" + m.group(1).lower(), s)


def resolve(brand, v):
    """(hex '#RRGGBB', alpha) for a colour token."""
    if isinstance(v, dict):
        hex_, _ = resolve(brand, v["hex"])
        return hex_, float(v["alpha"])
    m = re.fullmatch(r"\{brand\.(\w+)\}", v)
    hex_ = brand[m.group(1)] if m else v
    if not re.fullmatch(r"#[0-9A-Fa-f]{6}", hex_):
        sys.exit(f"bad colour {v!r}")
    return hex_.upper(), 1.0


def colours(brand, node, prefix=()):
    """Flatten a theme's colour tree to [(path tuple, hex, alpha)] in file order."""
    out = []
    for k, v in node.items():
        if isinstance(v, dict) and "hex" not in v:
            out += colours(brand, v, prefix + (k,))
        else:
            out.append((prefix + (k,), *resolve(brand, v)))
    return out


def qml_colour(hex_, alpha):
    if alpha >= 1.0:
        return hex_
    return "#%02X%s" % (round(alpha * 255), hex_[1:])  # QML wants #AARRGGBB


def css_colour(hex_, alpha):
    if alpha >= 1.0:
        return hex_
    r, g, b = (int(hex_[i:i + 2], 16) for i in (1, 3, 5))
    return f"rgba({r}, {g}, {b}, {alpha:g})"


def num(v):
    return f"{v:g}" if isinstance(v, float) else str(v)


def build(t):
    brand, themes, ty = t["brand"], t["themes"], t["type"]
    keys = list(themes)
    per_theme = {k: colours(brand, th["color"]) for k, th in themes.items()}
    paths = [p for p, _, _ in per_theme[keys[0]]]
    for k in keys:
        if [p for p, _, _ in per_theme[k]] != paths:
            sys.exit(f"theme {k} defines different colour tokens")
    scalars = ["typeDelta", "strokeScale", "targetMin", "blur"]
    for p in paths:
        if re.match(r"on[A-Z]", camel(*p)):
            sys.exit(f"token {'.'.join(p)} would be a QML signal handler name (on...): rename it")

    # ---- QML ----
    q = [f"// {HEADER}", "pragma Singleton", "import QtQuick", "", "QtObject {",
         "    /// Active theme key (one of themeKeys). Switch at runtime: Tokens.theme = \"daylight\".",
         f"    property string theme: \"{keys[0]}\"",
         "    readonly property var themeKeys: [" + ", ".join(f'"{k}"' for k in keys) + "]",
         "    readonly property var themeNames: ({ " + ", ".join(f'"{k}": "{themes[k]["name"]}"' for k in keys) + " })",
         "", "    readonly property var _themes: ({"]
    for i, k in enumerate(keys):
        entries = [f'"{camel(*p)}": "{qml_colour(h, a)}"' for p, h, a in per_theme[k]]
        entries += [f'"{s}": {json.dumps(themes[k][s])}' for s in scalars]
        q.append(f'        "{k}": {{')
        q += [f"            {e}," for e in entries[:-1]] + [f"            {entries[-1]}"]
        q.append("        }" + ("," if i < len(keys) - 1 else ""))
    q += ["    })", f'    readonly property var _t: _themes[theme] !== undefined ? _themes[theme] : _themes["{keys[0]}"]',
          "", "    // Colours (theme-dependent)"]
    q += [f"    readonly property color {camel(*p)}: _t.{camel(*p)}" for p in paths]
    q += ["", "    // Typography (sizes in pt; Daylight adds typeDelta)"]
    for role, fams in ty["family"].items():
        q.append(f'    readonly property string {camel("font", role)}: "{fams[0]}"')
        q.append(f"    readonly property var {camel('font', role, 'families')}: {json.dumps(fams)}")
    q += [f"    readonly property int {camel('weight', k)}: {v}" for k, v in ty["weight"].items()]
    q += [f"    readonly property real {camel('size', k)}: {v} + _t.typeDelta" for k, v in ty["sizePt"].items()]
    q += [f"    readonly property real {camel('lineHeight', k)}: {num(v)}" for k, v in ty["lineHeight"].items()]
    q += [f"    readonly property real titleTrackingPx: {num(ty['titleTrackingPx'])}",
          f"    readonly property var telemetryFeatures: {json.dumps(ty['telemetryFeatures'])}",
          "", "    // Layout and motion (px, ms)"]
    q += [f"    readonly property real {camel('space', k)}: {num(v)}" for k, v in t["spacePx"].items()]
    q += [f"    readonly property real {camel('radius', k)}: {num(v)}" for k, v in t["radiusPx"].items()]
    q += [f"    readonly property real {camel('stroke', k)}: {num(v)} * _t.strokeScale" for k, v in t["strokePx"].items()]
    q += [f"    readonly property int {camel('motion', k)}: {v}" for k, v in t["motionMs"].items()]
    q += [f"    readonly property real {camel('opacity', k)}: {num(v)}" for k, v in t["opacity"].items()]
    q += ["    readonly property real targetMin: _t.targetMin", "    readonly property bool blur: _t.blur", "}", ""]
    qml = "\n".join(q)
    qmldir = f"# {HEADER}\nmodule DrorControl.Tokens\nsingleton Tokens 1.0 Tokens.qml\n"

    # ---- CSS ----
    c = [f"/* {HEADER} */", ":root {"]
    for role, fams in ty["family"].items():
        generic = "monospace" if role == "telemetry" else "sans-serif"
        c.append(f"  --dc-font-{kebab(role)}: " + ", ".join(f'"{f}"' for f in fams) + f", {generic};")
    c += [f"  --dc-weight-{kebab(k)}: {v};" for k, v in ty["weight"].items()]
    c += [f"  --dc-line-height-{kebab(k)}: {num(v)};" for k, v in ty["lineHeight"].items()]
    c.append(f"  --dc-title-tracking: {num(ty['titleTrackingPx'])}px;")
    c.append("  --dc-telemetry-features: " + ", ".join(f'"{f}"' for f in ty["telemetryFeatures"]) + ";")
    c += [f"  --dc-space-{kebab(k)}: {num(v)}px;" for k, v in t["spacePx"].items()]
    c += [f"  --dc-radius-{kebab(k)}: {num(v)}px;" for k, v in t["radiusPx"].items()]
    c += [f"  --dc-motion-{kebab(k)}: {v}ms;" for k, v in t["motionMs"].items()]
    c += [f"  --dc-opacity-{kebab(k)}: {num(v)};" for k, v in t["opacity"].items()]
    c.append("}")
    for i, k in enumerate(keys):
        th = themes[k]
        sel = f'[data-theme="{kebab(k)}"]'
        c += ["", f":root, {sel} {{" if i == 0 else f"{sel} {{"]
        c += [f"  --dc-color-{'-'.join(kebab(x) for x in p)}: {css_colour(h, a)};" for p, h, a in per_theme[k]]
        c += [f"  --dc-size-{kebab(s)}: {v + th['typeDelta']}pt;" for s, v in ty["sizePt"].items()]
        c += [f"  --dc-stroke-{kebab(s)}: {num(v * th['strokeScale'])}px;" for s, v in t["strokePx"].items()]
        c.append(f"  --dc-target-min: {th['targetMin']}px;")
        c.append("}")
    css = "\n".join(c) + "\n"
    return {"qml/DrorControl/Tokens/Tokens.qml": qml, "qml/DrorControl/Tokens/qmldir": qmldir,
            "tokens.css": css}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    files = build(json.loads(SRC.read_text(encoding="utf-8")))
    stale = [n for n, text in files.items()
             if not (OUT / n).exists() or (OUT / n).read_text(encoding="utf-8") != text]
    if a.check:
        if stale:
            sys.exit(f"design tokens out of date ({', '.join(stale)}): run python3 scripts/gen_tokens.py")
        print("design tokens up to date")
        return
    for n, text in files.items():
        (OUT / n).parent.mkdir(parents=True, exist_ok=True)
        (OUT / n).write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {', '.join(f'ui/tokens/generated/{n}' for n in files)}")


if __name__ == "__main__":
    main()
