#!/usr/bin/env python3
"""Generate docs/reference/cli/dc-cli.md from `dc-cli --help` of every subcommand.

Usage: python3 scripts/gen_cli_docs.py [--bin PATH] [--check]
Builds nothing: point --bin at a dc-cli binary (default target/debug/dc-cli, built with
`cargo build -p dc-cli`). --check exits 1 if the page is out of date.
"""
import argparse
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "docs/reference/cli/dc-cli.md"

INTRO = """# dc-cli reference

`dc-cli` is DrorControl's command-line tool: the same Rust core as the app, for scripting,
bench tests and post-flight analysis. Generated by `scripts/gen_cli_docs.py` from the tool's
own `--help`; run it again after changing a command.

Commands that read logs work on a file and never touch a vehicle. Commands that talk to a
vehicle (`params`, `mission download`, `log list`/`download`, `telemetry`, `cot`, `daemon`)
open the link given with `--connect` (for example `tcp:127.0.0.1:5760`, `udp:0.0.0.0:14550`,
`serial:/dev/tty.usbmodem1:115200`).

## Common tasks

| Task | Command |
|---|---|
| Everything about a flight log | `dc-cli log report FLIGHT.BIN` |
| Health checks for CI (non-zero exit on a warning) | `dc-cli log health FLIGHT.BIN --json --fail-on warning` |
| Health from telemetry only | `dc-cli tlog health FLIGHT.tlog` |
| Share a log without revealing where it was flown | `dc-cli log sanitize FLIGHT.BIN --out SHARE.BIN` (`tlog sanitize` for recordings) |
| Make a log smaller (the armed time only) | `dc-cli log trim FLIGHT.BIN --out SHORT.BIN` |
| Track for Google Earth, by flight mode | `dc-cli log export FLIGHT.BIN --kml FLIGHT.kml` |
| Parameters that switch off safety nets | `dc-cli params-review FLIGHT.BIN` |

Never commit field logs with real positions to the repository; sanitize them first
(ADR-0012).

"""


def help_text(binary, args):
    out = subprocess.run([binary, *args, "--help"], capture_output=True, text=True, check=True)
    return out.stdout.rstrip() + "\n"


def subcommands(text):
    m = re.search(r"^Commands:\n(.*?)(?:\n\n|\Z)", text, re.S | re.M)
    if not m:
        return []
    names = []
    for line in m.group(1).splitlines():
        parts = line.split()
        if parts and parts[0] != "help":
            names.append(parts[0])
    return names


def render(binary):
    sections = []

    def walk(path):
        text = help_text(binary, path)
        title = " ".join(["dc-cli", *path])
        level = "#" * min(2 + len(path), 4)
        sections.append(f"{level} `{title}`\n\n```text\n{text}```\n")
        for sub in subcommands(text):
            walk([*path, sub])

    walk([])
    return INTRO + "\n".join(sections)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bin", default=str(ROOT / "target/debug/dc-cli"))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    page = render(a.bin)
    if a.check:
        if not OUT.exists() or OUT.read_text() != page:
            print(f"{OUT.relative_to(ROOT)} is out of date: run scripts/gen_cli_docs.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(page)
    print(f"wrote {OUT.relative_to(ROOT)} ({page.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
